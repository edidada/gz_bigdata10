drop table class_attendance;
CREATE TABLE class_attendance (
    dateinfo      longtext        comment '日期',
    class_id        longtext           comment '班级id',
   studying_student_count decimal(10,2)  comment '在读班级人数',
    morning_att_count       decimal(10,2)         comment '上午出勤人数',
   morning_att_ratio       decimal(10,2)         comment '上午出勤率',
    afternoon_att_count      decimal(10,2)        comment '下午出勤人数',
   afternoon_att_ratio      decimal(10,2)        comment '下午出勤率',
    evening_att_count       decimal(10,2)        comment '晚自习出勤人数',
   evening_att_ratio       decimal(10,2)        comment '晚自习出勤率',
   morning_late_count       decimal(10,2)        comment '上午迟到人数',
   morning_late_ratio       decimal(10,2)        comment '上午迟到率',
    afternoon_late_count     decimal(10,2)        comment '下午迟到人数',
   afternoon_late_ratio     decimal(10,2)        comment '下午迟到率',
    evening_late_count       decimal(10,2)        comment '晚自习迟到人数',
   evening_late_ratio       decimal(10,2)        comment '晚自习迟到率',
   morning_leave_count       decimal(10,2)       comment '上午请假人数',
   morning_leave_ratio       decimal(10,2)       comment '上午请假率',
    afternoon_leave_count    decimal(10,2)        comment '下午请假人数',
   afternoon_leave_ratio    decimal(10,2)        comment '下午请假率',
    evening_leave_count       decimal(10,2)        comment '晚自习请假人数',
   evening_leave_ratio       decimal(10,2)        comment '晚自习请假率',
    morning_truant_count       decimal(10,2)          comment '上午旷课人数',
   morning_truant_ratio       decimal(10,2)          comment '上午旷课率',
    afternoon_truant_count   decimal(10,2)        comment '下午旷课人数',
   afternoon_truant_ratio   decimal(10,2)        comment '下午旷课率',
    evening_truant_count       decimal(10,2)        comment '晚自习旷课人数',
   evening_truant_ratio       decimal(10,2)        comment '晚自习旷课率')
engine=innodb default charset ='utf8';
select * from class_attendance