  shunt_employee_group_id int COMMENT '所属分流员工组',
  ends_time string
  )comment '客户关系表'
partitioned by (start_time string)
clustered by (customer_relationship_id) sorted by (customer_relationship_id) into 10 buckets
row format delimited fields terminated by '\t'
stored as orc tblproperties('orc.compress'='SNAPPY');



insert into edu_dwd.fact_customer_clue partition (start_time)
select 
    id ,
    year(create_date_time)  yearinfo,
    month(create_date_time) monthinfo,
    day(create_date_time) dayinfo,
    hour(create_date_time) hourinfo,
    update_date_time ,
    deleted ,
    customer_id ,
    customer_relationship_id ,
    session_id ,
    sid ,
    status ,
    `user` ,
    create_time ,
    platform ,
    s_name ,
    seo_source ,
    seo_keywords ,
    ip ,
    referrer ,
    from_url ,
    landing_page_url ,
    url_title ,
    to_peer ,
    manual_time ,
    begin_time ,
    reply_msg_count ,
    total_msg_count ,
    msg_count ,
    `comment` ,
    finish_reason ,
    finish_user ,
    end_time ,
    platform_description ,
    browser_name ,
    os_info ,
    area ,
    country ,
    province ,
    city ,
    creator ,
    name ,
    idcard ,
    phone ,
    
    if(itcast_school_id = 0 or itcast_school_id is null,-1,
    itcast_school_id)
    as itcast_school_id
    ,
    
    itcast_school ,
    case 
    when itcast_subject_id = 0
    then -1
    when itcast_subject_id is null
    then -1
    else itcast_subject_id
    end as
    itcast_subject_id
    ,
    
    itcast_subject ,
    wechat ,
    qq ,
    email ,
    gender ,
    level ,
    origin_type ,
    information_way ,
    working_years ,
    technical_directions ,
    customer_state ,
    valid ,
    anticipat_signup_date ,
    
    case clue_state 
    when 'VALID_NEW_CLUES'
    then '新客户'
    when 'VALID_PUBLIC_NEW_CLUE'
    then '老客户'
    else '无效客户'
    end as clue_state_stat
    ,
    scrm_department_id ,
    superior_url ,
    superior_source ,
    landing_url ,
    landing_source ,
    info_url ,
    info_source ,
    origin_channel ,
    course_id ,
    course_name ,
    zhuge_session_id ,
    is_repeat ,
    tenant ,
    activity_id ,
    activity_name ,
    follow_type ,
    shunt_mode_id ,
    shunt_employee_group_id,
    '9999-99-99' ends_time,
    if(update_date_time is not null and update_date_time !='',
    substring(update_date_time,1,10),
    substring(create_time,1,10)) as
    start_time 

from edu_ods.customer_clue;
